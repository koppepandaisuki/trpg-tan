/** 能力値の「どれくらい?」の目安。版で尺度が違う。 */
export function abilityScale(edition: CoCEdition): string {
  return edition === "7"
    ? "目安: 50 が平均的な大人。70以上で得意、90以上は並外れた才能。15以下はかなり苦手。"
    : "目安: 10〜11 が平均。16以上で優秀、3〜4 はかなり苦手。判定では値×5が成功率%になる。";
}

export function abilitySectionHint(edition: CoCEdition): string {
  return (
    "キャラの素質を表す数値。各項目の ? にカーソルを乗せると意味が見られます。\n" +
    abilityScale(edition)
  );
}

